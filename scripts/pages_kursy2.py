def dlist(items):
    return '<div class="dlist"><ul>' + ''.join(
        f'<li>{ico(i)}<span>{T(t)}</span></li>' for i, t in items) + '</ul></div>'

def cards2(items):
    return '<div class="grid2">' + ''.join(
        f'<div class="card">{ico(i, "ic big")}<h3>{T(h)}</h3><p>{T(d)}</p></div>'
        for i, h, d in items) + '</div>'

def steps(items):
    return '<ul class="stepline">' + ''.join(
        f'<li><span class="nom">{n+1}</span>{ico(i)}<div class="txt"><h3>{T(h)}</h3><p>{T(d)}</p></div></li>'
        for n, (i, h, d) in enumerate(items)) + '</ul>'

def voprosy(items):
    out = ''
    for q, a in items:
        ps = ''.join(f'<p>{T(p)}</p>' for p in a)
        out += f"""<details class="vopros"><summary>{ico('strela')}<span>{T(q)}</span></summary>
<div class="otvet">{ps}</div></details>"""
    return out

